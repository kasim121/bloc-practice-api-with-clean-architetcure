/// Definition: a data type describes what kind of value a variable holds.
void main() {
  final String title = 'Dart basics';
  final int lessonCount = 9;
  final double completion = 0.5;
  final bool isPublished = true;

  print('Title: $title');
  print('Lessons: $lessonCount');
  print('Completion: $completion');
  print('Published: $isPublished');
}
